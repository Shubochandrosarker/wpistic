#!/usr/bin/env node
/**
 * Generates wpistic-platform/.env.staging — the single source of truth for the
 * local Docker staging stack (docker-compose.staging.yml).
 *
 * Every value it writes is a throwaway, local-only value: the two RSA
 * keypairs are freshly generated for this checkout, billing stays FREE_ONLY,
 * and the Postgres password is the same one docker-compose.yml has always
 * used. Nothing here is a real credential.
 *
 * Usage (from wpistic-platform/):
 *   node docker/generate-staging-env.mjs           # write .env.staging if absent
 *   node docker/generate-staging-env.mjs --force   # regenerate, rotating keys
 */
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = join(ROOT, '.env.staging');
const force = process.argv.includes('--force');

if (existsSync(TARGET) && !force) {
  console.log('.env.staging already exists — pass --force to regenerate.');
  process.exit(0);
}

/** RS256 keypair, PEM-encoded, newlines escaped so the value survives .env parsing. */
function rsaPair() {
  const { privateKey, publicKey } = generateKeyPairSync('rsa', {
    modulusLength: 2048,
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
    publicKeyEncoding: { type: 'spki', format: 'pem' },
  });
  const escape = (pem) => pem.trim().replace(/\r?\n/g, '\\n');
  return { private: escape(privateKey), public: escape(publicKey) };
}

const account = rsaPair();
const license = rsaPair();
const hex = (n) => randomBytes(n).toString('hex');

writeFileSync(
  TARGET,
  `# ---------------------------------------------------------------------------
# WPistic local staging environment — consumed by docker-compose.staging.yml.
#
# GENERATED by docker/generate-staging-env.mjs. Throwaway local-only values:
# freshly generated RSA keypairs, FREE_ONLY billing, and the same Postgres
# password docker-compose.yml has always used. Nothing here is a real secret
# and nothing here may be reused outside a laptop.
#
# Regenerate (rotates every key):  node docker/generate-staging-env.mjs --force
# ---------------------------------------------------------------------------

# --- Postgres ---------------------------------------------------------------
POSTGRES_USER=wpistic
POSTGRES_PASSWORD=password
POSTGRES_DB=wpistic
# Host port for the staging database. 5433 so it can coexist with the plain
# docker-compose.yml dev database already bound to 5432.
POSTGRES_HOST_PORT=5433
# In-network URL used by the migrate job and the Hyperdrive local binding.
DATABASE_URL=postgresql://wpistic:password@postgres:5432/wpistic

# --- Host-visible ports -----------------------------------------------------
API_PORT=8787
ACCOUNT_PORT=8788
DASHBOARD_PORT=5173
ADMIN_PORT=4321

# --- account worker vars ----------------------------------------------------
# ISSUER must match the \`issuer\` the API checks when verifying access tokens,
# i.e. it has to equal ACCOUNT_SERVICE_URL below.
ISSUER=http://localhost:8788
COOKIE_DOMAIN=localhost
DEFAULT_REDIRECT=http://localhost:5173

# --- api worker vars --------------------------------------------------------
ACCOUNT_SERVICE_URL=http://localhost:8788
PUBLIC_API_URL=http://localhost:8787
PUBLIC_ACCOUNT_URL=http://localhost:8788
PUBLIC_DASHBOARD_URL=http://localhost:5173
PUBLIC_ADMIN_URL=http://localhost:4321
BILLING_MODE=FREE_ONLY
DASHBOARD_URL=http://localhost:5173
ADMIN_EMAILS=owner@wpistic.local,staff@wpistic.local
# Staff role ladder: support_agent < billing_admin < platform_admin < super_admin.
# Unlisted allowlisted staff default to support_agent.
ADMIN_ROLES=owner@wpistic.local=super_admin,staff@wpistic.local=support_agent
ALLOW_LEGACY_ADMIN_TOKEN=true

# --- frontend build-time vars ----------------------------------------------
VITE_API_URL=http://localhost:8787
VITE_ACCOUNT_URL=http://localhost:8788
ADMIN_API_URL=http://api:8787
ADMIN_ACCOUNT_URL=http://account:8788
ADMIN_CLIENT_ID=wpistic_admin
ADMIN_REDIRECT_URI=http://localhost:4321/auth/callback
PUBLIC_ACCOUNT_URL=http://localhost:8788

# --- shared secrets ---------------------------------------------------------
# RS256 keypair: account.wpistic.com signs access tokens, the API verifies
# them. PEMs carry literal \\n; the apps expand them via normalizePem().
JWT_PRIVATE_KEY=${account.private}
JWT_PUBLIC_KEY=${account.public}

# Separate RS256 keypair for license activation tokens (distinct audience).
LICENSE_JWT_PRIVATE_KEY=${license.private}
LICENSE_JWT_PUBLIC_KEY=${license.public}

# HMAC master key for license validation response signatures.
LICENSE_SIGNING_SECRET=${hex(32)}

# AES-GCM key (base64, 32 bytes) encrypting TOTP secrets at rest.
MFA_ENC_KEY=${randomBytes(32).toString('base64')}

# Local release automation only; the admin portal uses OAuth staff JWTs.
ADMIN_API_TOKEN=${hex(32)}

# --- Stripe ---------------------------------------------------------------
# Stripe is intentionally absent. Local staging runs in FREE_ONLY mode;
# authorized payment administrators inject real test secrets only when needed.
`
);

console.log(`Wrote ${TARGET}`);
